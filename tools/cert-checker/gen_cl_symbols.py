#!/usr/bin/env python3
# Generates cl_symbols.h from the quoted list in the definition of
# acl2::*common-lisp-symbols-from-main-lisp-package* in axioms.lisp.
# Usage: python3 gen_cl_symbols.py <ACL2 source dir> > cl_symbols.h
import sys, os

src = os.path.join(sys.argv[1], "axioms.lisp")
lines = open(src, encoding="utf-8", errors="replace").read().split("\n")
start = next(i for i, l in enumerate(lines)
             if l.startswith("(acl2::defconst acl2::*common-lisp-symbols-from-main-lisp-package*"))
toks = []
opened = False
done = False
for l in lines[start + 1:]:
    if done:
        break
    if l.startswith(";"):
        continue
    for t in l.split():
        if not opened:
            if t.startswith("'("):
                opened = True
                t = t[2:]
                if not t:
                    continue
            else:
                continue
        if t.endswith(")"):
            t = t.rstrip(")")
            if t:
                toks.append(t)
            done = True
            break
        toks.append(t)

names = sorted(set(t.upper() for t in toks))
print("/* Generated by gen_cl_symbols.py from axioms.lisp, acl2::*common-lisp-symbols-from-main-lisp-package*. */")
print("static const char *const CL_SYMBOLS[] = {")
for n in names:
    assert '"' not in n and "\\" not in n and "|" not in n, n
    print('  "%s",' % n)
print("};")
print("static const int CL_SYMBOLS_COUNT = %d;" % len(names))
